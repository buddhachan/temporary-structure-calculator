import assert from 'node:assert/strict';
import {solveSupportedBeam as solve} from './beam-supports.js';
const near=(a,b,t=0.02)=>assert.ok(Math.abs(a-b)<=t,`expected ${a} ~= ${b}`);
const base={L:6,E:205000,I:80000000};
const P=20,L=6,EI=205000*80000000;
let r=solve({...base,support:'simple',pointLoads:[{P,a:3}]});
near(r.RA,10);near(r.RB,10);near(r.maxMoment,30);near(r.maxShear,10);
near(r.maxDeflection,20000*6000**3/(48*EI),.01);
near(r.leftMoment,0);near(r.rightMoment,0);
r=solve({...base,support:'cantilever-left',pointLoads:[{P,a:L}]});
near(r.RA,20);near(r.RB,0);near(Math.abs(r.leftMoment),120);near(r.maxDeflection,20000*6000**3/(3*EI),.05);
r=solve({...base,support:'fixed-fixed',pointLoads:[{P,a:3}]});
near(r.RA,10);near(r.RB,10);near(Math.abs(r.leftMoment),15);near(Math.abs(r.rightMoment),15);
near(r.maxDeflection,20000*6000**3/(192*EI),.02);
r=solve({...base,support:'fixed-pinned',pointLoads:[{P,a:3}]});
near(r.RA+r.RB,20);near(r.RB,6.875,.05);near(Math.abs(r.leftMoment),18.75,.05);
r=solve({...base,support:'simple',patchLoads:[{w:4,a:0,b:6}]});
near(r.RA,12);near(r.RB,12);near(r.maxMoment,18,.05);
near(r.maxDeflection,5*4*6000**4/(384*EI),.02);
assert.throws(()=>solve({...base,support:'invalid'}));
console.log('FEM analytical reference checks passed');
